"""
FHIR-style resource construction - simulated, never transmitted.

Scope and honesty
    These are FHIR-*shaped* JSON documents for a demo clinician panel. Nothing
    in this module opens a socket. There is no FHIR server, no real endpoint,
    no dispatch, and no emergency service is contacted. Every resource carries
    a `meta.tag` of HTEST ("test health data") per the HL7 v3 ActReason value
    set, which is the standard way to mark data that must never be treated as
    a real clinical record.

Terminology
    Codes use a local code system (`http://auracare.example/CodeSystem/...`)
    rather than invented LOINC or SNOMED codes. A production integration needs
    a real terminology binding agreed with the receiving system; guessing codes
    here would produce documents that look conformant and are not. The one
    place a standard coding is used is the HTEST security tag, which is real.

Structure
    build_bundle() assembles: one QuestionnaireResponse (PHQ-8), one
    Observation per graded indicator, one RiskAssessment, and - only when the
    assessment escalates - one CommunicationRequest with priority "stat".
"""

from __future__ import annotations

import hashlib
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from .phq8 import PHQ8_ITEMS, Phq8Result, RECALL_STEM, RESPONSE_OPTIONS
from .risk import (
    CRITICAL,
    ELEVATED,
    LEVEL_RANK,
    NOT_MEASURED,
    PATHWAY_CRISIS,
    PATHWAY_EMERGENCY,
    PATHWAY_LABEL,
    PATHWAY_ROUTINE,
    PATHWAY_URGENT,
    ScreeningAssessment,
)

CODE_SYSTEM = "http://auracare.example/CodeSystem/voice-screening"
IDENTIFIER_SYSTEM = "http://auracare.example/identifier/screening"

# Real HL7 coding: marks the resource as test data, not a clinical record.
HTEST_TAG = {
    "system": "http://terminology.hl7.org/CodeSystem/v3-ActReason",
    "code": "HTEST",
    "display": "test health data",
}

SIMULATION_BANNER = (
    "SIMULATED - generated by the Auracare screening prototype. Not a clinical "
    "record. No message was transmitted to any system or service."
)

# Units mapped to UCUM where a sensible one exists.
_UCUM = {
    "s": {"unit": "s", "system": "http://unitsofmeasure.org", "code": "s"},
    "%": {"unit": "%", "system": "http://unitsofmeasure.org", "code": "%"},
    "dB": {"unit": "dB", "system": "http://unitsofmeasure.org", "code": "dB"},
    "syll/s": {"unit": "syllables per second"},
    "/24": {"unit": "{score}"},
    "": {"unit": "{ratio}"},
}


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace(
        "+00:00", "Z"
    )


def _stable_id(prefix: str, *parts: str) -> str:
    """Deterministic id so repeated builds of the same data diff cleanly."""
    digest = hashlib.sha256("|".join(parts).encode("utf-8")).hexdigest()[:12]
    return f"{prefix}-{digest}"


def _meta() -> Dict[str, Any]:
    return {"security": [HTEST_TAG], "tag": [HTEST_TAG]}


def _subject(patient_id: str) -> Dict[str, Any]:
    return {"reference": f"Patient/{patient_id}", "display": f"Patient {patient_id}"}


