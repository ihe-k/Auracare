def questionnaire_response(
    phq8: Phq8Result,
    patient_id: str,
    authored: Optional[str] = None,
) -> Dict[str, Any]:
    """PHQ-8 responses as a QuestionnaireResponse."""
    authored = authored or _now_iso()
    items: List[Dict[str, Any]] = []
    for item in PHQ8_ITEMS:
        value = phq8.item_scores.get(item.key)
        entry: Dict[str, Any] = {"linkId": item.key, "text": item.text}
        if value is None:
            entry["answer"] = []
        else:
            entry["answer"] = [
                {
                    "valueCoding": {
                        "system": f"{CODE_SYSTEM}/phq8-response",
                        "code": str(value),
                        "display": RESPONSE_OPTIONS[value],
                    }
                }
            ]
        items.append(entry)

    return {
        "resourceType": "QuestionnaireResponse",
        "id": _stable_id("phq8", patient_id, authored),
        "meta": _meta(),
        "status": "completed" if phq8.complete else "in-progress",
        "subject": _subject(patient_id),
        "authored": authored,
        "questionnaire": f"{CODE_SYSTEM}/Questionnaire/phq8",
        "text": {
            "status": "generated",
            "div": f"<div xmlns=\"http://www.w3.org/1999/xhtml\">{RECALL_STEM}</div>",
        },
        "item": items,
        "extension": [
            {
                "url": f"{CODE_SYSTEM}/phq8-total",
                "valueInteger": phq8.total_score,
            },
            {
                "url": f"{CODE_SYSTEM}/phq8-band",
                "valueString": phq8.band,
            },
            {
                "url": f"{CODE_SYSTEM}/phq8-prorated",
                "valueBoolean": phq8.prorated,
            },
            {
                "url": f"{CODE_SYSTEM}/scoring-method",
                "valueString": (
                    "Simple summation of 8 items (0-3 each). Bands and the "
                    "cut-point of 10 per Kroenke et al. 2009."
                ),
            },
        ],
    }


def indicator_observation(
    indicator,
    task_id: int,
    task_title: str,
    patient_id: str,
    effective: Optional[str] = None,
) -> Dict[str, Any]:
    """One graded acoustic indicator as an Observation."""
    effective = effective or _now_iso()
    unit_info = _UCUM.get(indicator.unit, {"unit": indicator.unit or "{ratio}"})

    resource: Dict[str, Any] = {
        "resourceType": "Observation",
        "id": _stable_id("obs", patient_id, indicator.key, effective),
        "meta": _meta(),
        "status": "preliminary",
        "category": [
            {
                "coding": [
                    {
                        "system": "http://terminology.hl7.org/CodeSystem/observation-category",
                        "code": "exam",
                        "display": "Exam",
                    }
                ]
            }
        ],
        "code": {
            "coding": [
                {
                    "system": CODE_SYSTEM,
                    "code": indicator.key,
                    "display": indicator.label,
                }
            ],
            "text": indicator.label,
        },
        "subject": _subject(patient_id),
        "effectiveDateTime": effective,
        "method": {
            "text": f"Task {task_id}: {task_title} (acoustic analysis, experimental)"
        },
    }

    if indicator.value is None:
        resource["dataAbsentReason"] = {
            "coding": [
                {
                    "system": "http://terminology.hl7.org/CodeSystem/data-absent-reason",
                    "code": "not-performed",
                    "display": "Not Performed",
                }
            ],
            "text": "measurement could not be taken from the recording",
        }
    else:
        resource["valueQuantity"] = {
            "value": round(float(indicator.value), 4),
            **unit_info,
        }

    resource["interpretation"] = [
        {
            "coding": [
                {
                    "system": f"{CODE_SYSTEM}/risk-level",
                    "code": indicator.level.lower().replace(" ", "-"),
                    "display": indicator.level,
                }
            ],
            "text": indicator.detail or indicator.level,
        }
    ]
    resource["note"] = [
        {
            "text": (
                "Graded against provisional prototype thresholds, not validated "
                "clinical cut-offs."
            )
        }
    ]
    return resource


def risk_assessment(
    assessment: ScreeningAssessment,
    patient_id: str,
    occurrence: Optional[str] = None,
) -> Dict[str, Any]:
    """The triage outcome as a RiskAssessment."""
    occurrence = occurrence or _now_iso()
    predictions = []
    if assessment.phq8 is not None and assessment.phq8.scorable:
        predictions.append(
            {
                "outcome": {
                    "text": f"Depression severity (PHQ-8): {assessment.phq8.band}"
                },
                "qualitativeRisk": {
                    "coding": [
                        {
                            "system": f"{CODE_SYSTEM}/phq8-band",
                            "code": str(assessment.phq8.band_index),
                            "display": assessment.phq8.band,
                        }
                    ]
                },
                "rationale": (
                    f"PHQ-8 total {assessment.phq8.total_score}/24 scored by "
                    "summation against published cut-points."
                ),
            }
        )

    return {
        "resourceType": "RiskAssessment",
        "id": _stable_id("risk", patient_id, occurrence),
        "meta": _meta(),
        "status": "final",
        "subject": _subject(patient_id),
        "occurrenceDateTime": occurrence,
        "method": {
            "text": "Auracare four-domain voice screening prototype"
        },
        "code": {
            "coding": [
                {
                    "system": CODE_SYSTEM,
                    "code": "voice-screening-triage",
                    "display": "Voice screening triage outcome",
                }
            ]
        },
        "prediction": predictions,
        "mitigation": "; ".join(assessment.clinician_actions) or "none",
        "note": [
            {"text": SIMULATION_BANNER},
            {
                "text": (
                    f"Overall indicator level: {assessment.overall_level}. "
                    f"Pathway: {PATHWAY_LABEL.get(assessment.primary_pathway, '')}. "
                    f"{assessment.n_tasks_measured} of 4 tasks measured."
                )
            },
        ]
        + [{"text": r} for r in assessment.reasons],
    }


def communication_request(
    assessment: ScreeningAssessment,
    patient_id: str,
    authored: Optional[str] = None,
) -> Dict[str, Any]:
    """
    The simulated dispatch message.

    Priority is "stat" for the respiratory-emergency and crisis pathways,
    "urgent" for urgent review, "routine" otherwise.
    """
    authored = authored or _now_iso()

    if assessment.primary_pathway in (PATHWAY_EMERGENCY, PATHWAY_CRISIS):
        priority = "stat"
    elif assessment.primary_pathway == PATHWAY_URGENT:
        priority = "urgent"
    else:
        priority = "routine"

    if assessment.primary_pathway == PATHWAY_EMERGENCY:
        recipient = "Organization/emergency-triage-queue"
        content = (
            "SIMULATED STAT: respiratory safety threshold breached during "
            "bioacoustic voice screening. "
            + " ".join(assessment.reasons)
        )
    elif assessment.primary_pathway == PATHWAY_CRISIS:
        recipient = "Organization/mental-health-crisis-team"
        content = (
            "SIMULATED STAT: language indicating possible self-harm detected "
            "during voice screening. Transcript review required. Terms: "
            + ", ".join(assessment.safety_terms)
        )
    elif assessment.primary_pathway == PATHWAY_URGENT:
        recipient = "Organization/mental-health-team"
        content = (
            "SIMULATED URGENT: PHQ-8 in the severe band during voice screening. "
            + " ".join(assessment.reasons)
        )
    else:
        recipient = "Organization/primary-care-team"
        content = (
            "SIMULATED ROUTINE: voice screening complete. "
            + (" ".join(assessment.reasons) or "No indicators flagged.")
        )

    return {
        "resourceType": "CommunicationRequest",
        "id": _stable_id("comm", patient_id, assessment.primary_pathway, authored),
        "meta": _meta(),
        "identifier": [
            {"system": IDENTIFIER_SYSTEM, "value": f"auracare-{uuid.uuid4().hex[:10]}"}
        ],
        "status": "active",
        "intent": "order",
        "priority": priority,
        "category": [
            {
                "coding": [
                    {
                        "system": CODE_SYSTEM,
                        "code": assessment.primary_pathway,
                        "display": PATHWAY_LABEL.get(assessment.primary_pathway, ""),
                    }
                ]
            }
        ],
        "subject": _subject(patient_id),
        "authoredOn": authored,
        "recipient": [{"reference": recipient}],
        "payload": [
            {"contentString": content},
            {"contentString": SIMULATION_BANNER},
        ],
        "reasonCode": [
            {"text": reason} for reason in (assessment.reasons or ["routine screening"])
        ],
    }


def build_bundle(
    assessment: ScreeningAssessment,
    patient_id: str,
    timestamp: Optional[str] = None,
    include_normal_observations: bool = True,
) -> Dict[str, Any]:
    """
    Assemble the full document set for the clinician / EHR view.

    `include_normal_observations=False` keeps only indicators graded Elevated or
    Critical, which is what a real integration would usually send.
    """
    timestamp = timestamp or _now_iso()
    entries: List[Dict[str, Any]] = []

    def add(resource: Dict[str, Any]) -> None:
        entries.append(
            {
                "fullUrl": f"urn:uuid:{uuid.uuid5(uuid.NAMESPACE_URL, resource['id'])}",
                "resource": resource,
            }
        )

    if assessment.phq8 is not None:
        add(questionnaire_response(assessment.phq8, patient_id, timestamp))

    for task in assessment.tasks:
        for indicator in task.indicators:
            if not include_normal_observations:
                if LEVEL_RANK.get(indicator.level, -1) < LEVEL_RANK[ELEVATED]:
                    continue
            add(
                indicator_observation(
                    indicator, task.task_id, task.title, patient_id, timestamp
                )
            )

    add(risk_assessment(assessment, patient_id, timestamp))

    if assessment.primary_pathway != PATHWAY_ROUTINE or True:
        # Always emit one, so the routine case has a visible "nothing to do"
        # message rather than an empty panel.
        add(communication_request(assessment, patient_id, timestamp))

    return {
        "resourceType": "Bundle",
        "id": _stable_id("bundle", patient_id, timestamp),
        "meta": _meta(),
        "type": "collection",
        "timestamp": timestamp,
        "total": len(entries),
        "entry": entries,
    }


def summarise_bundle(bundle: Dict[str, Any]) -> Dict[str, int]:
    """Count resources by type, for the panel header."""
    counts: Dict[str, int] = {}
    for entry in bundle.get("entry", []):
        rtype = entry.get("resource", {}).get("resourceType", "Unknown")
        counts[rtype] = counts.get(rtype, 0) + 1
    return counts


