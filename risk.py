"""
Risk indicators, triage routing and patient-facing messages.

Design notes worth knowing before changing anything here:

*   Indicators are graded against the *provisional* thresholds only. The
    clinical reference values in `config.py` are never branched on.

*   A measurement that could not be taken is `None`, not zero, and a `None`
    never contributes a risk level. This is the difference between "your
    phonation was 0.0 s, escalating" and "we could not measure your phonation,
    please try again" - the first is a false alarm generated by a failed
    recording, and it is exactly what an energy threshold on a silent file
    produces if you let it.

*   Escalation is a *set* of pathways, not one enum. A patient can
    simultaneously trip the respiratory intercept and disclose self-harm, and
    those route to different places. Collapsing them into a single worst-case
    value loses the second one.

*   Depression severity comes from the PHQ-8 sum against published cut-points.
    The repository's severity model is not consulted; see `severity_model.py`
    for why.
"""

