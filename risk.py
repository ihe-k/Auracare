def assess_screening(
    task1=None,
    task2=None,
    task3=None,
    task4=None,
    phq8: Optional[Phq8Result] = None,
    thresholds: Optional[Thresholds] = None,
) -> ScreeningAssessment:
    """
    Combine task results into a triage decision and the two views' content.

    Order of precedence for the banner: respiratory emergency, then mental
    health crisis, then urgent review, then routine review. All applicable
    pathways are retained in `pathways`.
    """
    t = thresholds or Thresholds()
    out = ScreeningAssessment(phq8=phq8)

    out.tasks = [
        assess_task1(task1, t),
        assess_task2(task2, t),
        assess_task3(task3, t),
        assess_task4(task4, phq8, t),
    ]
    out.n_tasks_measured = sum(1 for a in out.tasks if a.measured)
    out.overall_level = worst(a.level for a in out.tasks)

    pathways: List[str] = []

    # -- intercepts, routed by what they actually measure -------------------
    fluency_intercept = False
    for a in out.tasks:
        if a.intercept_triggered and a.intercept_reason:
            out.reasons.append(f"Task {a.task_id}: {a.intercept_reason}")
            if a.task_id in RESPIRATORY_INTERCEPT_TASKS:
                if PATHWAY_EMERGENCY not in pathways:
                    pathways.append(PATHWAY_EMERGENCY)
            elif a.task_id in FLUENCY_INTERCEPT_TASKS:
                fluency_intercept = True
                if PATHWAY_URGENT not in pathways:
                    pathways.append(PATHWAY_URGENT)

    # -- self-harm disclosure ----------------------------------------------
    lang = getattr(task4, "language", None)
    if lang is not None and getattr(lang, "safety_critical", False):
        out.safety_critical = True
        out.safety_terms = list(lang.safety_terms)
        pathways.append(PATHWAY_CRISIS)
        out.reasons.append(
            "Language suggesting self-harm or suicidal ideation was detected in "
            f"the Task 4 transcript: {', '.join(out.safety_terms)}"
        )

    # -- PHQ-8 -------------------------------------------------------------
    if phq8 is not None and phq8.scorable and phq8.total_score is not None:
        if phq8.band_index >= 4:
            pathways.append(PATHWAY_URGENT)
            out.reasons.append(
                f"PHQ-8 total {phq8.total_score}/24 is in the severe band"
            )
        elif phq8.clinically_significant:
            pathways.append(PATHWAY_REVIEW)
            out.reasons.append(
                f"PHQ-8 total {phq8.total_score}/24 is at or above the "
                "case-finding cut-point of 10"
            )
        if phq8.elevated_items:
            labels = [item_by_key(k).short for k in phq8.elevated_items]
            out.reasons.append(
                "PHQ-8 items endorsed at 'more than half the days' or higher: "
                + ", ".join(labels)
            )

    # -- elevated acoustic indicators --------------------------------------
    elevated = [
        f"Task {a.task_id} ({a.title}) graded {a.level}"
        for a in out.tasks
        if LEVEL_RANK.get(a.level, -1) >= LEVEL_RANK[ELEVATED]
    ]
    if elevated:
        if PATHWAY_REVIEW not in pathways:
            pathways.append(PATHWAY_REVIEW)
        out.reasons.extend(elevated)

    if not pathways:
        pathways.append(PATHWAY_ROUTINE)

    out.pathways = [p for p in PATHWAY_PRIORITY if p in pathways]
    out.primary_pathway = out.pathways[0]

    # -- patient-facing messages -------------------------------------------
    msgs: List[str] = []
    if PATHWAY_EMERGENCY in out.pathways:
        msgs.append(
            "Based on your check-in, your breathing sounds strained. We are "
            "routing your assessment to emergency triage now. Please stay on "
            "the line. If you are in severe distress, call 999 straight away."
        )
    if PATHWAY_CRISIS in out.pathways:
        msgs.append(
            "Some of what you said suggests you may be having thoughts of "
            "harming yourself. Please talk to someone about this today - you "
            "deserve support. " + CRISIS_RESOURCES_UK
        )
    if fluency_intercept and PATHWAY_EMERGENCY not in out.pathways:
        msgs.append(
            "You paused quite a lot while describing the picture. That can "
            "happen for many ordinary reasons - thinking, tiredness, or simply "
            "not being sure what to say - so it is not a result on its own. "
            "We are passing it to a clinician to look at alongside everything "
            "else."
        )
    if phq8 is not None and phq8.scorable:
        msgs.append(PHQ8_PATIENT_MESSAGES[phq8.band_index])
        if phq8.band_index >= 3 and PATHWAY_CRISIS not in out.pathways:
            msgs.append(CRISIS_RESOURCES_UK)
    if not msgs:
        msgs.append(
            "Check-in complete. Nothing in today's results needs follow-up. "
            "Your results have been added to your health record."
        )
    if out.n_tasks_measured < 4:
        msgs.append(
            f"Note: {4 - out.n_tasks_measured} of the 4 tasks could not be "
            "measured from your recordings. Re-recording those would give a "
            "more complete picture."
        )
    msgs.append(
        "This is a screening prototype, not a diagnosis. Only a qualified "
        "clinician can assess your health."
    )
    out.patient_messages = msgs

    # -- clinician actions -------------------------------------------------
    actions: List[str] = []
    if PATHWAY_EMERGENCY in out.pathways:
        actions.append(
            "SIMULATED: STAT dispatch raised to the emergency triage queue. "
            "Review the acoustic evidence before acting - a short phonation "
            "can also mean the patient stopped early or the recording was cut."
        )
    if PATHWAY_CRISIS in out.pathways:
        actions.append(
            "Self-harm language detected in the transcript. Review the "
            "transcript verbatim: the lexicon cannot distinguish disclosure "
            "from quotation, negation or hypothetical speech. Follow local "
            "risk-assessment policy."
        )
    if fluency_intercept:
        actions.append(
            "Task 4 pause ratio over the configured threshold. CALIBRATION "
            "WARNING: measured across 76 thirty-second windows of the sample "
            "recordings, this indicator ranged 0.24-0.72 with a median of "
            "0.48. The protocol's 0.45 threshold is therefore below the median "
            "of ordinary speech and fired on 57% of windows. As specified it "
            "cannot separate a struggling patient from an ordinary one. Treat "
            "it as a prompt to listen to the recording, not as a finding, and "
            "recalibrate against your own Task 4 samples "
            "(scripts/calibrate_pause_ratio.py) before relying on it."
        )
    if PATHWAY_URGENT in out.pathways and phq8 is not None and phq8.scorable \
            and phq8.band_index >= 4:
        actions.append(
            "PHQ-8 in the severe band. Note PHQ-8 omits the self-harm item, so "
            "a direct risk assessment is still required."
        )
    if PATHWAY_REVIEW in out.pathways:
        actions.append(
            "Add to the routine review list. Acoustic indicators are "
            "experimental and provisional; weight the PHQ-8 and clinical "
            "history above them."
        )
    if out.primary_pathway == PATHWAY_ROUTINE:
        actions.append("No action indicated. Store the observation set.")
    out.clinician_actions = actions

    return out


