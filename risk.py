# ---------------------------------------------------------------------------
# Indicator
# ---------------------------------------------------------------------------
@dataclass
class Indicator:
    """One graded measurement."""

    key: str
    label: str
    value: Optional[float]
    unit: str
    level: str
    detail: str = ""
    higher_is_worse: bool = True

    def as_dict(self) -> Dict[str, object]:
        return {
            "key": self.key,
            "label": self.label,
            "value": None if self.value is None else round(float(self.value), 4),
            "unit": self.unit,
            "level": self.level,
            "detail": self.detail,
        }


def _grade(
    value: Optional[float],
    warn: float,
    high: float,
    higher_is_worse: bool = True,
    critical: Optional[float] = None,
) -> str:
    """Grade one value against two or three thresholds."""
    if value is None:
        return NOT_MEASURED
    if higher_is_worse:
        if critical is not None and value >= critical:
            return CRITICAL
        if value >= high:
            return ELEVATED
        if value >= warn:
            return BORDERLINE
        return NORMAL
    if critical is not None and value <= critical:
        return CRITICAL
    if value <= high:
        return ELEVATED
    if value <= warn:
        return BORDERLINE
    return NORMAL


# ---------------------------------------------------------------------------
# Task assessment
# ---------------------------------------------------------------------------
@dataclass
class TaskAssessment:
    """Graded result for one of the four tasks."""

    task_id: int
    title: str
    level: str = NOT_MEASURED
    indicators: List[Indicator] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    measured: bool = False
    intercept_triggered: bool = False
    intercept_reason: Optional[str] = None

    def as_dict(self) -> Dict[str, object]:
        return {
            "task_id": self.task_id,
            "title": self.title,
            "level": self.level,
            "measured": self.measured,
            "intercept_triggered": self.intercept_triggered,
            "intercept_reason": self.intercept_reason,
            "indicators": [i.as_dict() for i in self.indicators],
            "notes": list(self.notes),
        }


def assess_task1(result, thresholds: Thresholds) -> TaskAssessment:
    """Grade sustained phonation."""
    t = thresholds
    out = TaskAssessment(task_id=1, title="Respiratory & laryngeal health")
    if result is None:
        return out

    out.notes = list(getattr(result, "notes", []))
    dur = result.phonation_duration_s if result.phonation_duration_s > 0 else None
    out.measured = dur is not None

    out.indicators.append(
        Indicator(
            key="phonation_duration_s",
            label="Sustained phonation time",
            value=dur,
            unit="s",
            level=_grade(
                dur,
                warn=t.get("task1", "phonation_target_s"),
                high=t.get("task1", "phonation_low_s"),
                higher_is_worse=False,
                critical=t.get("task1", "phonation_critical_s"),
            ),
            detail=(
                f"critical < {t.get('task1', 'phonation_critical_s')} s, "
                f"low < {t.get('task1', 'phonation_low_s')} s, "
                f"target >= {t.get('task1', 'phonation_target_s')} s"
            ),
            higher_is_worse=False,
        )
    )

    v = result.voice

    # Jitter and shimmer are only graded when the recording is clean enough
    # for them to describe the voice rather than the room. The published norms
    # come from studio recordings; applying them to a noisy consumer
    # microphone grades nearly every speaker abnormal, which is worse than
    # useless - it buries the indicators that do mean something.
    reliable = getattr(v, "perturbation_reliable", True)
    noisy_detail = (
        "not graded: recording too noisy for perturbation measures "
        f"(HNR {v.hnr_db:.1f} dB)" if (not reliable and v.hnr_db is not None)
        else "not graded: recording too noisy for perturbation measures"
    )

    out.indicators.append(
        Indicator(
            key="jitter_local_pct",
            label="Jitter (local)",
            value=v.jitter_local_pct,
            unit="%",
            level=(
                _grade(
                    v.jitter_local_pct,
                    warn=t.get("task1", "jitter_warn_pct"),
                    high=t.get("task1", "jitter_high_pct"),
                )
                if reliable
                else NOT_MEASURED
            ),
            detail=(
                f"warn >= {t.get('task1', 'jitter_warn_pct')} %"
                if reliable else noisy_detail
            ),
        )
    )
    out.indicators.append(
        Indicator(
            key="shimmer_local_pct",
            label="Shimmer (local)",
            value=v.shimmer_local_pct,
            unit="%",
            level=(
                _grade(
                    v.shimmer_local_pct,
                    warn=t.get("task1", "shimmer_warn_pct"),
                    high=t.get("task1", "shimmer_high_pct"),
                )
                if reliable
                else NOT_MEASURED
            ),
            detail=(
                f"warn >= {t.get('task1', 'shimmer_warn_pct')} %"
                if reliable else noisy_detail
            ),
        )
    )
    out.indicators.append(
        Indicator(
            key="hnr_db",
            label="Harmonics-to-noise ratio",
            value=v.hnr_db,
            unit="dB",
            level=_grade(
                v.hnr_db,
                warn=t.get("task1", "hnr_warn_db"),
                high=t.get("task1", "hnr_low_db"),
                higher_is_worse=False,
            ),
            detail=f"warn <= {t.get('task1', 'hnr_warn_db')} dB",
            higher_is_worse=False,
        )
    )
    # Pitch variability is gated on the same condition: in a noisy recording
    # the tracker makes octave errors, which produce a large CV that reflects
    # the tracking failure rather than the speaker's pitch control.
    out.indicators.append(
        Indicator(
            key="f0_cv",
            label="Pitch variability (CV)",
            value=result.f0_cv,
            unit="",
            level=(
                _grade(
                    result.f0_cv,
                    warn=t.get("task1", "f0_cv_warn"),
                    high=t.get("task1", "f0_cv_warn") * 2.0,
                )
                if reliable
                else NOT_MEASURED
            ),
            detail=(
                f"warn >= {t.get('task1', 'f0_cv_warn')}"
                if reliable else noisy_detail
            ),
        )
    )

    out.level = worst(i.level for i in out.indicators)

    critical_s = t.get("task1", "phonation_critical_s")
    if dur is not None and dur < critical_s:
        out.intercept_triggered = True
        out.intercept_reason = (
            f"sustained phonation {dur:.2f} s is below the {critical_s} s "
            "respiratory safety threshold"
        )
    return out


def assess_task2(result, thresholds: Thresholds) -> TaskAssessment:
    """Grade forced exhalation."""
    t = thresholds
    out = TaskAssessment(task_id=2, title="Expiratory airway dynamics")
    if result is None:
        return out

    out.notes = list(getattr(result, "notes", []))
    dur = (
        result.exhalation_duration_s if result.exhalation_duration_s > 0 else None
    )
    out.measured = dur is not None

    # Two-sided: too short means the manoeuvre failed, too long suggests
    # obstruction. A single-sided grade would call a prolonged - and clinically
    # more interesting - exhalation "normal".
    critical_s = t.get("task2", "exhalation_critical_s")
    low_s = t.get("task2", "exhalation_low_s")
    normal_max_s = t.get("task2", "exhalation_normal_max_s")
    prolonged_s = t.get("task2", "exhalation_prolonged_s")

    if dur is None:
        duration_level = NOT_MEASURED
    elif dur < critical_s:
        duration_level = CRITICAL
    elif dur < low_s:
        duration_level = ELEVATED
    elif dur < low_s * 1.3:
        duration_level = BORDERLINE
    elif dur <= normal_max_s:
        duration_level = NORMAL
    elif dur <= prolonged_s:
        duration_level = BORDERLINE
    else:
        duration_level = ELEVATED

    out.indicators.append(
        Indicator(
            key="exhalation_duration_s",
            label="Exhalation duration",
            value=dur,
            unit="s",
            level=duration_level,
            detail=(
                f"critical < {critical_s} s, short < {low_s} s, "
                f"prolonged > {prolonged_s} s"
            ),
            higher_is_worse=False,
        )
    )
    out.indicators.append(
        Indicator(
            key="rise_time_s",
            label="Rise time to peak",
            value=result.rise_time_s,
            unit="s",
            level=_grade(
                result.rise_time_s,
                warn=t.get("task2", "rise_time_warn_s"),
                high=t.get("task2", "rise_time_high_s"),
            ),
            detail=f"warn >= {t.get('task2', 'rise_time_warn_s')} s",
        )
    )
    out.indicators.append(
        Indicator(
            key="wheeze_index_db",
            label="Tonal peak prominence (wheeze proxy)",
            value=result.wheeze_index_db,
            unit="dB",
            level=_grade(
                result.wheeze_index_db,
                warn=t.get("task2", "wheeze_index_warn_db"),
                high=t.get("task2", "wheeze_index_high_db"),
            ),
            detail=f"warn >= {t.get('task2', 'wheeze_index_warn_db')} dB",
        )
    )

    out.level = worst(i.level for i in out.indicators)

    critical_s = t.get("task2", "exhalation_critical_s")
    if dur is not None and dur < critical_s:
        out.intercept_triggered = True
        out.intercept_reason = (
            f"forced exhalation {dur:.2f} s is below the {critical_s} s "
            "airway safety threshold"
        )
    return out


def assess_task3(result, thresholds: Thresholds) -> TaskAssessment:
    """Grade diadochokinetic rate."""
    t = thresholds
    out = TaskAssessment(task_id=3, title="Neuromotor speech control")
    if result is None:
        return out

    out.notes = list(getattr(result, "notes", []))
    rate = result.syllable_rate_hz
    enough = result.n_syllables >= int(t.get("task3", "min_syllables"))
    out.measured = rate is not None

    out.indicators.append(
        Indicator(
            key="syllable_rate_hz",
            label="Syllable repetition rate",
            value=rate,
            unit="syll/s",
            level=_grade(
                rate,
                warn=t.get("task3", "ddk_rate_low_hz") + 1.0,
                high=t.get("task3", "ddk_rate_low_hz"),
                higher_is_worse=False,
                critical=t.get("task3", "ddk_rate_critical_hz"),
            ),
            detail=f"low < {t.get('task3', 'ddk_rate_low_hz')} syll/s",
            higher_is_worse=False,
        )
    )
    out.indicators.append(
        Indicator(
            key="rhythm_cv",
            label="Rhythm variability (CV)",
            value=result.rhythm_cv if enough else None,
            unit="",
            level=_grade(
                result.rhythm_cv if enough else None,
                warn=t.get("task3", "rhythm_cv_warn"),
                high=t.get("task3", "rhythm_cv_high"),
            ),
            detail=f"warn >= {t.get('task3', 'rhythm_cv_warn')}",
        )
    )
    out.indicators.append(
        Indicator(
            key="n_syllables",
            label="Syllables detected",
            value=float(result.n_syllables),
            unit="",
            level=NORMAL if enough else BORDERLINE,
            detail=f"at least {int(t.get('task3', 'min_syllables'))} expected",
            higher_is_worse=False,
        )
    )

    out.level = worst(i.level for i in out.indicators)
    return out


def assess_task4(
    result,
    phq8: Optional[Phq8Result],
    thresholds: Thresholds,
) -> TaskAssessment:
    """Grade connected speech, including PHQ-8 and language flags."""
    t = thresholds
    out = TaskAssessment(task_id=4, title="Cognitive & language fluency")
    if result is None:
        return out

    out.notes = list(getattr(result, "notes", []))
    out.measured = bool(result.has_speech)

    pause_ratio = result.pause_ratio if result.has_speech else None
    out.indicators.append(
        Indicator(
            key="pause_ratio",
            label="Speech pause ratio",
            value=pause_ratio,
            unit="",
            level=_grade(
                pause_ratio,
                warn=t.get("task4", "pause_ratio_warn"),
                high=t.get("task4", "pause_ratio_critical"),
                critical=t.get("task4", "pause_ratio_critical"),
            ),
            detail=(
                f"warn >= {t.get('task4', 'pause_ratio_warn')}, "
                f"critical >= {t.get('task4', 'pause_ratio_critical')}"
            ),
        )
    )

    rate = result.speech_rate_sylls
    rate_level = NOT_MEASURED
    if rate is not None:
        low = t.get("task4", "speech_rate_low_sylls")
        high = t.get("task4", "speech_rate_high_sylls")
        if rate < low or rate > high:
            rate_level = ELEVATED
        elif rate < low * 1.3 or rate > high * 0.9:
            rate_level = BORDERLINE
        else:
            rate_level = NORMAL
    out.indicators.append(
        Indicator(
            key="speech_rate_sylls",
            label="Speech rate",
            value=rate,
            unit="syll/s",
            level=rate_level,
            detail=(
                f"expected {t.get('task4', 'speech_rate_low_sylls')}"
                f"-{t.get('task4', 'speech_rate_high_sylls')} syll/s"
            ),
        )
    )

    out.indicators.append(
        Indicator(
            key="lexical_diversity",
            label="Lexical diversity (information density proxy)",
            value=result.lexical_diversity,
            unit="",
            level=_grade(
                result.lexical_diversity,
                warn=t.get("task4", "lexical_diversity_low") * 1.2,
                high=t.get("task4", "lexical_diversity_low"),
                higher_is_worse=False,
            ),
            detail=f"low <= {t.get('task4', 'lexical_diversity_low')}",
            higher_is_worse=False,
        )
    )

    lang: LanguageFlags = result.language
    neg_ratio = lang.negative_ratio if lang.analysed else None
    out.indicators.append(
        Indicator(
            key="negative_language_ratio",
            label="Negative-language share of speech",
            value=neg_ratio,
            unit="",
            level=_grade(
                neg_ratio,
                warn=t.get("task4", "negative_language_warn"),
                high=t.get("task4", "negative_language_high"),
            ),
            detail=f"warn >= {t.get('task4', 'negative_language_warn')}",
        )
    )
    out.indicators.append(
        Indicator(
            key="first_person_singular_ratio",
            label="First-person singular pronoun share",
            value=lang.first_person_singular_ratio if lang.analysed else None,
            unit="",
            level=_grade(
                lang.first_person_singular_ratio if lang.analysed else None,
                warn=t.get("task4", "first_person_singular_warn"),
                high=t.get("task4", "first_person_singular_warn") * 1.6,
            ),
            detail=f"warn >= {t.get('task4', 'first_person_singular_warn')}",
        )
    )

    if phq8 is not None and phq8.scorable:
        phq_level = [NORMAL, BORDERLINE, ELEVATED, ELEVATED, CRITICAL][phq8.band_index]
        out.indicators.append(
            Indicator(
                key="phq8_total",
                label="PHQ-8 total score",
                value=float(phq8.total_score or 0),
                unit="/24",
                level=phq_level,
                detail=f"{phq8.band}; clinically significant >= 10",
            )
        )

    out.level = worst(i.level for i in out.indicators)

    critical_ratio = t.get("task4", "pause_ratio_critical")
    if pause_ratio is not None and pause_ratio > critical_ratio:
        out.intercept_triggered = True
        out.intercept_reason = (
            f"pause ratio {pause_ratio:.2f} exceeds the {critical_ratio} "
            "safety threshold"
        )
    return out


# ---------------------------------------------------------------------------
# Overall screening assessment
# ---------------------------------------------------------------------------
@dataclass
class ScreeningAssessment:
    """Everything the two views need to render."""

    tasks: List[TaskAssessment] = field(default_factory=list)
    phq8: Optional[Phq8Result] = None
    overall_level: str = NOT_MEASURED
    pathways: List[str] = field(default_factory=list)
    primary_pathway: str = PATHWAY_ROUTINE
    reasons: List[str] = field(default_factory=list)
    patient_messages: List[str] = field(default_factory=list)
    clinician_actions: List[str] = field(default_factory=list)
    safety_critical: bool = False
    safety_terms: List[str] = field(default_factory=list)
    n_tasks_measured: int = 0

    @property
    def is_emergency(self) -> bool:
        return PATHWAY_EMERGENCY in self.pathways

    @property
    def needs_escalation(self) -> bool:
        return self.primary_pathway not in (PATHWAY_ROUTINE, PATHWAY_REVIEW)

    def task(self, task_id: int) -> Optional[TaskAssessment]:
        for t in self.tasks:
            if t.task_id == task_id:
                return t
        return None

    def as_dict(self) -> Dict[str, object]:
        return {
            "overall_level": self.overall_level,
            "pathways": list(self.pathways),
            "primary_pathway": self.primary_pathway,
            "primary_pathway_label": PATHWAY_LABEL.get(self.primary_pathway, ""),
            "is_emergency": self.is_emergency,
            "safety_critical": self.safety_critical,
            "safety_terms": list(self.safety_terms),
            "reasons": list(self.reasons),
            "n_tasks_measured": self.n_tasks_measured,
            "phq8": self.phq8.as_dict() if self.phq8 else None,
            "tasks": [t.as_dict() for t in self.tasks],
            "patient_messages": list(self.patient_messages),
            "clinician_actions": list(self.clinician_actions),
        }


