# ---------------------------------------------------------------------------
# Levels
# ---------------------------------------------------------------------------
NORMAL = "Normal"
BORDERLINE = "Borderline"
ELEVATED = "Elevated"
CRITICAL = "Critical"
NOT_MEASURED = "Not measured"

LEVEL_RANK: Dict[str, int] = {
    NOT_MEASURED: -1,
    NORMAL: 0,
    BORDERLINE: 1,
    ELEVATED: 2,
    CRITICAL: 3,
}

LEVEL_COLOUR: Dict[str, str] = {
    NOT_MEASURED: "#64748b",
    NORMAL: "#10b981",
    BORDERLINE: "#f59e0b",
    ELEVATED: "#f97316",
    CRITICAL: "#ef4444",
}


def worst(levels) -> str:
    """Highest level present, ignoring unmeasured ones."""
    graded = [l for l in levels if l in LEVEL_RANK and l != NOT_MEASURED]
    if not graded:
        return NOT_MEASURED
    return max(graded, key=lambda l: LEVEL_RANK[l])


